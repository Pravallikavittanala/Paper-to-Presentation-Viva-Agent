
from pathlib import Path
from reportlab.lib.pagesizes import A4
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
from reportlab.lib.styles import getSampleStyleSheet
from docx import Document
from pptx import Presentation
from pptx.util import Inches, Pt


def create_pdf(content, filename="paper_report.pdf"):
    doc = SimpleDocTemplate(filename, pagesize=A4)
    styles = getSampleStyleSheet()
    story = []

    for line in content.split("\n"):
        if line.strip():
            story.append(Paragraph(line, styles["BodyText"]))
            story.append(Spacer(1, 8))

    doc.build(story)
    return filename


def create_docx(content, filename="paper_report.docx"):
    doc = Document()
    doc.add_heading("Research Paper Report", 0)

    for line in content.split("\n"):
        if line.strip():
            doc.add_paragraph(line)

    doc.save(filename)
    return filename



def create_pptx(content, filename="paper_presentation.pptx"):
    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)

    lines = [line.strip() for line in content.split("\n") if line.strip()]

    # Title slide
    slide = prs.slides.add_slide(prs.slide_layouts[0])
    slide.shapes.title.text = "Research Paper Presentation"
    slide.placeholders[1].text = (
        "Generated by Paper-to-Presentation & Viva Agent"
    )

    # Prepare presentation sections
    sections = []
    current_title = "Overview"
    current_points = []

    for line in lines:
        clean_line = line.replace("**", "").replace("*", "").strip()

        if clean_line.startswith("#"):
            if current_points:
                sections.append((current_title, current_points))
            current_title = clean_line.lstrip("#").strip()
            current_points = []

        elif clean_line.endswith(":") and len(clean_line) < 100:
            if current_points:
                sections.append((current_title, current_points))
            current_title = clean_line.rstrip(":")
            current_points = []

        else:
            clean_line = clean_line.lstrip("-• ").strip()
            if clean_line:
                current_points.append(clean_line)

    if current_points:
        sections.append((current_title, current_points))

    # Create editable slides
    for title, points in sections:
        for start in range(0, len(points), 5):
            slide = prs.slides.add_slide(prs.slide_layouts[1])
            slide.shapes.title.text = title

            text_frame = slide.placeholders[1].text_frame
            text_frame.clear()

            for point in points[start:start + 5]:
                paragraph = (
                    text_frame.paragraphs[0]
                    if not text_frame.paragraphs[0].text
                    else text_frame.add_paragraph()
                )
                paragraph.text = point
                paragraph.level = 0
                paragraph.font.size = Pt(20)

    # Final slide
    slide = prs.slides.add_slide(prs.slide_layouts[5])
    slide.shapes.title.text = "Thank You"

    prs.save(filename)
    return filename
